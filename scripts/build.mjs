#!/usr/bin/env node
/**
 * Build both halves. The browser half is optional while the panel is being
 * built out, so a missing `src/client/index.ts` skips it instead of failing.
 *
 *   node scripts/build.mjs            # everything that exists
 *   node scripts/build.mjs --node     # Node half only
 *   node scripts/build.mjs --client   # browser half only
 */
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { build } from 'esbuild'

const require = createRequire(import.meta.url)
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const clientEntry = [join(root, 'src', 'client', 'index.ts'), join(root, 'src', 'client', 'index.tsx')]
  .find((candidate) => existsSync(candidate))

const clientOnly = process.argv.includes('--client')
const nodeOnly = process.argv.includes('--node')

/** Provided by the DSH client runtime; never bundled. */
const CLIENT_EXTERNAL = ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client']

if (!clientOnly) {
  const tsc = require.resolve('typescript/bin/tsc')
  execFileSync(process.execPath, [tsc, '-p', 'tsconfig.json'], { cwd: root, stdio: 'inherit' })
  console.log('[build] node half → lib/')
}

if (!nodeOnly) {
  if (!clientEntry) {
    console.log('[build] browser half skipped (src/client/index.tsx not present yet)')
  } else {
    const temporary = join(root, 'lib', '.client.bundle.cjs')
    const output = join(root, 'lib', 'client.js')
    mkdirSync(join(root, 'lib'), { recursive: true })

    await build({
      entryPoints: [clientEntry],
      outfile: temporary,
      bundle: true,
      format: 'cjs',
      platform: 'browser',
      target: 'es2022',
      jsx: 'automatic',
      minify: false,
      legalComments: 'none',
      logLevel: 'warning',
      external: CLIENT_EXTERNAL,
    })

    const body = readFileSync(temporary, 'utf8')
    writeFileSync(output, [
      '/* Generated by scripts/build.mjs — do not edit by hand. */',
      `window.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => {`,
      '    var module = { exports: {} }',
      '    var exports = module.exports',
      body,
      '    return module.exports',
      '} });',
      '',
    ].join('\n'), 'utf8')
    unlinkSync(temporary)
    console.log(`[build] browser half → lib/client.js (${pkg.name})`)
  }
}
